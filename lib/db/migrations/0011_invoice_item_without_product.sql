-- بند فاتورة بلا منتج.
--
-- `quotation_items.product_id` يقبل NULL منذ اليوم الأول، و`invoice_items`
-- كان `NOT NULL`. فكان النظام يسمح بكتابة عرض سعر بنوده مكتوبة بالإيد —
-- أعمال حفر وبرمجة وتثبيت، أو صنف لم يُدخَل الكتالوج بعد — ثم يرفض تحويل
-- ذلك العرض إلى فاتورة رفضًا كاملًا. اتفاقٌ يُكتب ولا يُفوَّتر.
--
-- ما لا منتج له لا مخزون له ولا تكلفة: مسارات المخزون تتخطى هذه السطور
-- صراحةً، فلا يُخصم شيء ولا يُرَد شيء عند الإلغاء.
--
-- إسقاط القيد وحده. المفتاح الأجنبي يبقى كما هو — NULL لا يخالفه.
--
-- مكتوبة يدويًا. آمنة وقابلة للتكرار.

ALTER TABLE "invoice_items" ALTER COLUMN "product_id" DROP NOT NULL;
