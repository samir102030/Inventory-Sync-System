-- إجمالي التركيب: ما يُحصَّل من العميل مقابل التركيب.
--
-- كان في المشروع رقم واحد اسمه `installation_cost` يُخصَم من الربح، فلم يكن
-- للتركيب إلا وجهٌ واحد: ما ندفعه. والتركيب في هذا النشاط بابُ دخلٍ قائم
-- بذاته — يُتفَق عليه في العقد ويُحصَّل، والفني يُدفع له من داخله.
--
-- فصلُ الوجهين يجعل ربح التركيب ظاهرًا وحده:
--   إجمالي التركيب − تكلفة التركيب
-- بدلًا من رقم واحد يبدو خسارة دائمًا مهما كان الاتفاق مربحًا.
--
-- الافتراضي '0' عن قصد: المشاريع القائمة لم يُسجَّل لها إجمالي، فلا نخترع
-- لها دخلًا لم يُدخَل. صافي ربحها يبقى كما كان حتى يكتبه صاحبه.
--
-- مكتوبة يدويًا. آمنة وقابلة للتكرار.

ALTER TABLE "projects"
  ADD COLUMN IF NOT EXISTS "installation_revenue" numeric(12, 2) NOT NULL DEFAULT '0';
